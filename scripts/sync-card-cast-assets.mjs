// Export only approved art; masters and the independent review library stay intact.
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url)),require=createRequire(import.meta.url);
const sharp=require(require.resolve('sharp',{paths:[root,path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules')]}));
const library=path.join(root,'art-preproduction/cast-fx-stage3');
const manifest=JSON.parse(await fs.readFile(path.join(library,'spec/manifest.json'),'utf8'));
const cardsDir=path.join(root,'dist/assets/cards'),fxDir=path.join(root,'dist/assets/card-cast');
await fs.mkdir(cardsDir,{recursive:true});await fs.mkdir(fxDir,{recursive:true});
const cardArt={},animations={},sizes={cards:0,cast:0};
for(const name of (await fs.readdir(path.join(root,'art-preproduction/card-reference-v3/cards'))).filter(n=>n.endsWith('.png')).sort()){
  const id=path.basename(name,'.png'),file=path.join(cardsDir,id+'.webp');
  await sharp(path.join(root,'art-preproduction/card-reference-v3/cards',name)).resize(512,768).webp({lossless:true,effort:6}).toFile(file);
  cardArt[id]='./assets/cards/'+id+'.webp';sizes.cards+=(await fs.stat(file)).size;
}
for(const [type,stages] of Object.entries(manifest.animations)){
  animations[type]={};
  for(const [stage,a] of Object.entries(stages)){
    const name=type+'-'+stage+'.webp',file=path.join(fxDir,name);
    await fs.copyFile(path.join(library,a.runtimeAtlas),file);sizes.cast+=(await fs.stat(file)).size;
    animations[type][stage]={url:'./assets/card-cast/'+name,frameCount:a.frameCount,frameMs:a.frameDurationMs,loop:a.loop,anchor:a.anchorPx,size:a.recommendedDrawSize};
  }
}
await fs.writeFile(path.join(root,'dist/card-cast-assets.mjs'),`// Generated by scripts/sync-card-cast-assets.mjs from the approved v3 art and Stage 3 library.\nexport const CARD_ART=${JSON.stringify(cardArt,null,2)};\nexport const CAST_ASSETS=${JSON.stringify(animations,null,2)};\nexport const CAST_FRAME_SIZE=256;\nexport const CAST_COLUMNS=4;\n`);
console.log(JSON.stringify({cards:Object.keys(cardArt).length,atlases:Object.values(animations).reduce((n,a)=>n+Object.keys(a).length,0),bytes:sizes}));
