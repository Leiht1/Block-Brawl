// Publish only the user-approved review selection. Keep source atlases unchanged.
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url)),review=root+'art-preproduction/skill-body-complete-v1/';
const m=JSON.parse(await fs.readFile(review+'manifest.json','utf8'));
if(!m.userApproved)throw Error('Skill selection must be approved before publishing.');
await fs.mkdir(root+'dist/assets/skill-body',{recursive:true});
const entries={};
for(const [id,e] of Object.entries(m.entries)){
 const name=e.reviewPath.split('/').at(-1).replace('_preview.','_final.');
 await fs.copyFile(review+e.reviewPath,root+'dist/assets/skill-body/'+name);
 entries[id]={url:'./assets/skill-body/'+name,mainMs:e.mainMs,alpha:e.renderAlpha??{},version:e.version};
 e.runtimePath='dist/assets/skill-body/'+name;e.status='final';e.userApproved=true;
}
const tile='tile_wild_star_soft_v1_final.png';
await fs.copyFile(review+m.specialTile.reviewPath,root+'dist/assets/skill-body/'+tile);
m.specialTile.runtimePath='dist/assets/skill-body/'+tile;m.specialTile.status='final';
m.status='integrated';m.integration='user-approved selection integrated into production; source previews retained';
m.stateStyles.sage.userApproved=true;m.stateStyles.sage.runtimePath='dist/effect_skill_body_soft_v1_final.mjs';
for(const e of Object.values(m.previewRules))e.productionChanged=true;
await fs.writeFile(review+'manifest.json',JSON.stringify(m,null,2)+'\n');
await fs.writeFile(root+'dist/skill-body-assets.mjs',`// Generated by scripts/sync-skill-body-assets.mjs from the approved selection.\nexport const SKILL_BODY_ENABLED=true;\nexport const SKILL_ASSETS=Object.freeze(${JSON.stringify(entries,null,2)});\nexport const WILD_TILE='./assets/skill-body/${tile}';\nexport const SKILL_LAYOUT=Object.freeze({frameSize:256,columns:4,rows:2,frames:8,anchor:[.5,.5]});\n`);
await fs.writeFile(root+'dist/assets/skill-body/manifest.json',JSON.stringify({approvedAt:'2026-10-12',direction:'方案C：克制雅致；颜色明确',status:'final',selection:'sage veil+backlight; quake row',entries,layout:{frameSize:[256,256],columns:4,rows:2,frames:8,anchor:[.5,.5]},wildTile:tile,sourceManifest:'art-preproduction/skill-body-complete-v1/manifest.json'},null,2)+'\n');
console.log('Published twelve approved skill atlases and rainbow tile.');
